// Contorller Funcitno to Run the Code 
// First build the Harnness File To run/compile it Directly

export async function runCode(req, res, next) {
  try {
    const { problemId, language, code, input } = req.validated.body;
    let execution = { code, input };

    if (problemId) {
      const problem = await Problem.findById(problemId).lean();
      if (!problem) {
        throw apiError(404, 'Problem not found');
      }

      execution = buildHarness({ problem, language, code, input });
    }

    const result = await executeCode({
      language,
      code: execution.code,
      input: execution.input
    });

    res.json({
      output: result.output,
      error: result.error
    });
  } catch (error) {
    next(error);
  }
}

/**
 * POST /run/batch
 *
 * Runs code against all visible sample test cases + any custom inputs.
 *
 * For SAMPLE cases:  expected output comes from the DB.
 * For CUSTOM cases:  expected output is generated by running the problem's
 *                    Python reference solution (if one exists) in parallel with
 *                    the user's code — same approach as LeetCode.
 */

// It run the Visible Test Cases and Hidden Test Cases
// It Runs visible test cases using expected result and compares
// It runs the Custom test cases and check it with host process Soltuion
export async function runBatch(req, res, next) {
  try {
    const { problemId, language, code, customCases = [] } = req.validated.body;

    const problem = await Problem.findById(problemId).lean();
    if (!problem) throw apiError(404, 'Problem not found');

    const refPython = problem.referenceSolution?.python || null;

    const sampleTestCases = await TestCase.find({ problemId: problem._id, isHidden: false })
      .sort({ order: 1, createdAt: 1 })
      .lean();

    /* ── helper: run a single piece of code against an input ── */
    async function runOne(lang, runCode, input, runOnHost = false) {
      const execution = buildHarness({ problem, language: lang, code: runCode, input });
      return executeCode({
        language: lang,
        code: execution.code,
        input: execution.input,
        timeoutMs: problem.timeLimitMs,
        runOnHost
      });
    }

    /* ── sample cases (expected output from DB) ─────────────── */
    const sampleResults = [];
    for (const tc of sampleTestCases) {
      try {
        const result = await runOne(language, code, tc.input);
        const actualOutput = result.ok ? (result.output ?? '') : null;
        const passed = result.ok
          ? normalizeOutput(actualOutput) === normalizeOutput(tc.expectedOutput)
          : null;
        sampleResults.push({
          input: tc.input,
          expectedOutput: tc.expectedOutput,
          output: actualOutput,
          error: result.ok ? null : (result.stderr || result.verdict || 'Execution failed'),
          verdict: result.verdict,
          passed,
          runtimeMs: result.runtimeMs
        });
      } catch (err) {
        sampleResults.push({
          input: tc.input,
          expectedOutput: tc.expectedOutput,
          output: null,
          error: err.message || 'Execution failed',
          verdict: null,
          passed: false,
          runtimeMs: 0
        });
      }
    }

    /* ── custom cases (expected output from reference solution) ─ */
    const customResults = [];
    for (const cc of customCases) {
      try {
        // Run user code (Docker) and reference solution (host) in parallel
        const tasks = [runOne(language, code, cc.input, false)];
        if (refPython) {
          tasks.push(runOne('python', refPython, cc.input, true));
        }
        const [userResult, refResult] = await Promise.all(tasks);

        const actualOutput    = userResult.ok ? (userResult.output ?? '') : null;
        const expectedOutput  = refResult?.ok ? (refResult.output ?? '')  : null;

        // passed: true/false only when we have both outputs
        const passed = actualOutput !== null && expectedOutput !== null
          ? normalizeOutput(actualOutput) === normalizeOutput(expectedOutput)
          : null;

        customResults.push({
          input: cc.input,
          expectedOutput,             // auto-generated by reference solution
          output: actualOutput,
          error: userResult.ok ? null : (userResult.stderr || userResult.verdict || 'Execution failed'),
          verdict: userResult.verdict,
          passed,
          runtimeMs: userResult.runtimeMs,
          hasReference: !!refPython   // tell the UI whether auto-check was possible
        });
      } catch (err) {
        customResults.push({
          input: cc.input,
          expectedOutput: null,
          output: null,
          error: err.message || 'Execution failed',
          verdict: null,
          passed: null,
          runtimeMs: 0,
          hasReference: false
        });
      }
    }

    res.json({ sampleResults, customResults });
  } catch (error) {
    next(error);
  }
}

// To judge and build all the HIdden Testcases when user Submits
export async function submitCode(req, res, next) {
  try {
    const { problemId, language, code } = req.validated.body;
    const userId = req.user?._id || req.user?.id;

    // Generate unique submission ID
    const submissionId = new mongoose.Types.ObjectId();

    // 1. Store transient pending status in Redis (expires in 10 minutes)
    await redisClient.set(
      `sub:status:${submissionId}`,
      JSON.stringify({ status: 'Pending' }),
      { EX: 600 }
    );

    // 2. Queue the code execution task
    await addSubmissionJob({
      submissionId,
      problemId,
      language,
      code,
      userId
    });

    res.json({
      submissionId,
      status: 'Pending'
    });
  } catch (error) {
    next(error);
  }
}

// Get the real-time status of a submission
export async function getSubmissionStatus(req, res, next) {
  try {
    const { submissionId } = req.validated.params;

    // 1. Query transient status in Redis
    const cachedStatus = await redisClient.get(`sub:status:${submissionId}`);
    if (cachedStatus) {
      return res.json(JSON.parse(cachedStatus));
    }

    // 2. Fallback to MongoDB if not present in Redis
    const submission = await Submission.findById(submissionId).lean();
    if (!submission) {
      throw apiError(404, 'Submission not found');
    }

    // Return mapped completed format to match transient format
    res.json({
      status: 'Completed',
      result: {
        verdict: submission.verdict,
        passed: submission.passed,
        total: submission.total,
        runtime: `${submission.runtimeMs}ms`,
        submissionId: submission._id,
        failedTest: submission.failedTest
      }
    });
  } catch (error) {
    next(error);
  }
}
